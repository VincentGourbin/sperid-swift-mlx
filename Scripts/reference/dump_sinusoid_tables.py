#!/usr/bin/env python3
"""Write Sources/IdolCore/Models/Layers/SinusoidalTables.swift: the exact fp32 frequencies torch computes
in SinusoidalEmbedder (`exp(-ln(max_period)·k/half)`), as bit patterns. torch's fp32 exp is not
correctly rounded (~1 ulp); the port uses the reference's own constants rather than a different
rounding of the same formula (effect on the real octree below the measurement, card T-1.5).

Usage: .venv-ref/bin/python -I Scripts/reference/dump_sinusoid_tables.py
"""
from pathlib import Path

import numpy as np
import torch

OUT = Path(__file__).resolve().parents[2] / "Sources/IdolCore/Models/Layers/SinusoidalTables.swift"


def table(max_period, half=128):
    f = torch.exp(-np.log(max_period) * torch.arange(start=0, end=half, dtype=torch.float32) / half)
    return [int(v) for v in f.numpy().view(np.uint32)]


def main():
    lines = ["// SinusoidalTables.swift - GENERATED by Scripts/reference/dump_sinusoid_tables.py, do not edit",
             "// The fp32 frequencies of `SinusoidalEmbedder` exactly as torch computes them (torch 2.15, CPU).",
             "", "enum SinusoidalTables {",
             "    /// maxPeriod → 128 frequencies (bit patterns of Float), for frequencyDim 256."]
    lines.append("    static let bits: [Double: [UInt32]] = [")
    for mp in (10000, 1024):
        vals = table(mp)
        lines.append(f"        {mp}: [")
        for i in range(0, len(vals), 8):
            lines.append("            " + ", ".join(f"0x{v:08x}" for v in vals[i:i + 8]) + ",")
        lines.append("        ],")
    lines += ["    ]", "", "    static func frequencies(maxPeriod: Double, half: Int) -> [Float]? {",
              "        guard half == 128, let b = bits[maxPeriod] else { return nil }",
              "        return b.map { Float(bitPattern: $0) }", "    }", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
