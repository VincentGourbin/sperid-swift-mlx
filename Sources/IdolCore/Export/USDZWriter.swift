import Foundation

/// AR Quick Look and RealityKit ignore vertex colours: the colours are baked into a texture where every quad
/// owns a `cell`×`cell` texel block (bilinear between its four vertex colours, texel centres on the corners,
/// so no bleeding between quads). The stage is written as USDA (valid inside a .usdz) next to the PNG.
public enum USDZWriter {
    public static func write(_ mesh: SplatMesh, to url: URL, cell: Int = 4) throws {
        let quads = mesh.quads.count
        let side = max(1, Int(Double(quads).squareRoot().rounded(.up)))
        let size = side * cell
        var atlas = RGBAImage(width: size, height: size)
        var st: [SIMD2<Float>] = []
        st.reserveCapacity(4 * quads)
        for (qi, q) in mesh.quads.enumerated() {
            let (cx, cy) = (qi % side, qi / side)
            let ids = [Int(q.x), Int(q.y), Int(q.z), Int(q.w)]
            let c = ids.map { mesh.colors[$0] }
            for ty in 0..<cell { for tx in 0..<cell {
                let u = Float(tx) / Float(cell - 1), v = Float(ty) / Float(cell - 1)
                let rgb = c[0] * ((1 - u) * (1 - v)) + c[1] * (u * (1 - v)) + c[2] * (u * v) + c[3] * ((1 - u) * v)
                let o = 4 * ((cy * cell + ty) * size + cx * cell + tx)
                atlas.pixels[o] = UInt8(max(0, min(255, (rgb.x * 255).rounded())))
                atlas.pixels[o + 1] = UInt8(max(0, min(255, (rgb.y * 255).rounded())))
                atlas.pixels[o + 2] = UInt8(max(0, min(255, (rgb.z * 255).rounded())))
                atlas.pixels[o + 3] = 255
            } }
            // corners (0,0) (1,0) (1,1) (0,1) of the cell, on texel centres; USD st has v up
            let corners: [(Float, Float)] = [(0, 0), (1, 0), (1, 1), (0, 1)]
            for k in 0..<4 {
                let px = Float(cx * cell) + 0.5 + corners[k].0 * Float(cell - 1)
                let py = Float(cy * cell) + 0.5 + corners[k].1 * Float(cell - 1)
                st.append(SIMD2(px / Float(size), 1 - py / Float(size)))
            }
        }
        let png = FileManager.default.temporaryDirectory.appendingPathComponent("idol-\(UUID()).png")
        defer { try? FileManager.default.removeItem(at: png) }
        try atlas.writePNG(to: png, opaque: true)
        let usda = stage(mesh, st: st)
        try USDZip.write([("Object.usda", Data(usda.utf8)), ("texture.png", try Data(contentsOf: png))], to: url)
    }

    static func floats(_ v: [SIMD3<Float>]) -> String {
        v.map { String(format: "(%.5g,%.5g,%.5g)", $0.x, $0.y, $0.z) }.joined(separator: ",")
    }

    /// Points and normals shared (vertex interpolation); the atlas UVs are per face corner (faceVarying).
    static func stage(_ mesh: SplatMesh, st: [SIMD2<Float>]) -> String {
        let counts = Array(repeating: "4", count: mesh.quads.count).joined(separator: ",")
        let indices = mesh.quads.map { "\($0.x),\($0.y),\($0.z),\($0.w)" }.joined(separator: ",")
        let points = mesh.positions, normals = mesh.normals
        let uv = st.map { String(format: "(%.5g,%.5g)", $0.x, $0.y) }.joined(separator: ",")
        return """
        #usda 1.0
        (
            defaultPrim = "Object"
            metersPerUnit = 1
            upAxis = "Y"
            doc = "Generated by sperid-swift-mlx (speridlabs/idol)"
        )

        def Xform "Object" (
            kind = "component"
        )
        {
            def Mesh "Mesh" (
                prepend apiSchemas = ["MaterialBindingAPI"]
            )
            {
                uniform bool doubleSided = 1
                int[] faceVertexCounts = [\(counts)]
                int[] faceVertexIndices = [\(indices)]
                rel material:binding = </Object/Material>
                normal3f[] normals = [\(floats(normals))] (
                    interpolation = "vertex"
                )
                point3f[] points = [\(floats(points))]
                texCoord2f[] primvars:st = [\(uv)] (
                    interpolation = "faceVarying"
                )
                uniform token subdivisionScheme = "none"
            }

            def Material "Material"
            {
                token outputs:surface.connect = </Object/Material/Surface.outputs:surface>

                def Shader "Surface"
                {
                    uniform token info:id = "UsdPreviewSurface"
                    color3f inputs:diffuseColor.connect = </Object/Material/Texture.outputs:rgb>
                    float inputs:metallic = 0
                    float inputs:roughness = 1
                    token outputs:surface
                }

                def Shader "Texture"
                {
                    uniform token info:id = "UsdUVTexture"
                    asset inputs:file = @texture.png@
                    token inputs:sourceColorSpace = "sRGB"
                    float2 inputs:st.connect = </Object/Material/St.outputs:result>
                    float3 outputs:rgb
                }

                def Shader "St"
                {
                    uniform token info:id = "UsdPrimvarReader_float2"
                    string inputs:varname = "st"
                    float2 outputs:result
                }
            }
        }

        """
    }
}

/// USDZ packaging: an uncompressed zip whose file data start on 64-byte boundaries (padding in the extra field).
enum USDZip {
    static let crcTable: [UInt32] = (0..<256).map { n in
        (0..<8).reduce(UInt32(n)) { c, _ in c & 1 != 0 ? 0xEDB8_8320 ^ (c >> 1) : c >> 1 }
    }

    static func crc32(_ d: Data) -> UInt32 {
        var c: UInt32 = 0xFFFF_FFFF
        for b in d { c = crcTable[Int((c ^ UInt32(b)) & 0xFF)] ^ (c >> 8) }
        return c ^ 0xFFFF_FFFF
    }

    static func write(_ files: [(String, Data)], to url: URL) throws {
        var out = Data(), central = Data()
        func le16(_ v: Int, _ d: inout Data) { var x = UInt16(v).littleEndian; d.append(Data(bytes: &x, count: 2)) }
        func le32(_ v: UInt32, _ d: inout Data) { var x = v.littleEndian; d.append(Data(bytes: &x, count: 4)) }
        for (name, data) in files {
            let nameData = Data(name.utf8), crc = crc32(data), offset = out.count
            let headerEnd = offset + 30 + nameData.count + 4                 // with an empty extra block header
            let pad = (64 - headerEnd % 64) % 64
            le32(0x0403_4B50, &out); le16(10, &out); le16(0, &out); le16(0, &out); le16(0, &out); le16(0, &out)
            le32(crc, &out); le32(UInt32(data.count), &out); le32(UInt32(data.count), &out)
            le16(nameData.count, &out); le16(4 + pad, &out); out.append(nameData)
            le16(0x1986, &out); le16(pad, &out); out.append(Data(count: pad))   // alignment extra field
            out.append(data)
            le32(0x0201_4B50, &central); le16(10, &central); le16(10, &central); le16(0, &central); le16(0, &central)
            le16(0, &central); le16(0, &central); le32(crc, &central); le32(UInt32(data.count), &central)
            le32(UInt32(data.count), &central); le16(nameData.count, &central); le16(0, &central); le16(0, &central)
            le16(0, &central); le16(0, &central); le32(0, &central); le32(UInt32(offset), &central); central.append(nameData)
        }
        let cdOffset = out.count
        out.append(central)
        le32(0x0605_4B50, &out); le16(0, &out); le16(0, &out); le16(files.count, &out); le16(files.count, &out)
        le32(UInt32(central.count), &out); le32(UInt32(cdOffset), &out); le16(0, &out)
        try out.write(to: url, options: .atomic)
    }
}
